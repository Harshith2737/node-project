"use strict";

const destinations = require("../../frontend/data/destinations.json");
const { api, method, sendJson, HttpError } = require("../../src/shared/http");

function normalize(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("en-IN");
}

function tokens(value) {
  return normalize(value).match(/[a-z0-9]+/g) || [];
}

function scoreDestination(destination, phrase, queryTokens) {
  const name = normalize(destination.name);
  const district = normalize(destination.district);
  const category = normalize(destination.category);
  const description = normalize(destination.description);
  const notes = normalize(destination.sourceNotes);
  const searchable = [name, district, category, description, notes].join(" ");

  let score = 0;
  if (name === phrase) score += 120;
  else if (name.includes(phrase)) score += 70;
  if (district === phrase) score += 65;
  else if (district.includes(phrase)) score += 45;
  if (category.includes(phrase)) score += 25;
  if (description.includes(phrase)) score += 15;

  for (const token of queryTokens) {
    if (name.includes(token)) score += 14;
    else if (district.includes(token)) score += 10;
    else if (category.includes(token)) score += 6;
    else if (description.includes(token)) score += 3;
    else if (notes.includes(token)) score += 1;
  }

  return searchable.includes(phrase) ? score : score;
}

module.exports = api(async (req, res) => {
  method(req, res, ["GET", "HEAD"]);

  const rawQuery = req.query?.q;
  if (typeof rawQuery !== "string") {
    throw new HttpError(400, "INVALID_QUERY", "Provide one search query using the q parameter.");
  }

  const query = rawQuery.trim();
  if (query.length < 2 || query.length > 80) {
    throw new HttpError(400, "INVALID_QUERY", "Search query must be between 2 and 80 characters.");
  }

  const normalizedQuery = normalize(query);
  const queryTokens = [...new Set(tokens(query))];
  if (queryTokens.length === 0) {
    throw new HttpError(400, "INVALID_QUERY", "Search query must contain letters or numbers.");
  }

  const data = destinations
    .map(destination => ({
      destination,
      score: scoreDestination(destination, normalizedQuery, queryTokens)
    }))
    .filter(item => item.score > 0)
    .sort((a, b) => b.score - a.score || a.destination.name.localeCompare(b.destination.name))
    .slice(0, 5)
    .map(({ destination }) => ({
      slug: destination.slug,
      name: destination.name,
      district: destination.district,
      category: destination.category,
      description: destination.description,
      officialSourceUrl: destination.officialSourceUrl,
      coordinateSourceUrl: destination.coordinateSourceUrl,
      sourceNotes: destination.sourceNotes,
      sourceReviewedOn: destination.sourceReviewedOn
    }));

  return sendJson(res, 200, {
    apiVersion: "v1",
    mode: "curated-catalogue-search",
    generativeAI: false,
    query,
    count: data.length,
    message: "Results are retrieved from reviewed destination records. They are not generated by an AI model.",
    data
  });
});
